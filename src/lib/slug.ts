// 2026-09-17 網址代碼(slug)去重複年度前綴。
//
// 背景:Sveltia CMS 的 classalbum 收藏,存檔檔名規則是 `{{year}}-{{fields.slug}}`
// (見 public/admin/config.yml)——年度前綴是刻意加的,目的是避免不同年度的活動
// 剛好取了同一個網址代碼(例如兩年都有人叫它 "sports-day")導致檔名互相覆蓋。
//
// 但這個前綴對「課程代碼」型的網址代碼是多餘的:課程代碼本身開頭就已經是年度數字
// (例如 1151c440 開頭的 115 本身就是年度),存檔檔名會變成 115-1151c440,如果直接
// 拿檔名當網址,最終網址會變成 /115/115-1151c440/,年度重複出現兩次,難看。
//
// 這裡不改 CMS 的存檔規則(那個年度前綴的防碰撞保護要留著,對「沒有代碼可用」的
// 活動類型很重要,見下面 albumUrlSlug 的呼叫端),而是只在「產生對外網址」這一步,
// 把檔名開頭剛好等於「目前年度-」的那一段拿掉——課程代碼類自然變乾淨
// (115-1151c440 → 1151c440),活動類的年度防碰撞機制完全不受影響(儲存檔名沒變,
// 只是網址顯示時省略掉那段,同一年度內同仁自己輸入的代碼還是不能重複,見 Sveltia
// 本身「同資料夾檔名不可重複」的內建限制)。
//
// 2026-07-29 之前用遷移腳本直接寫入的 82 筆 115 春季內容,檔名本來就沒有這個
// "115-" 前綴(直接是課程代碼本身,例如 1151c440.md)——這個函式對這批舊資料
// 是安全的no-op(id 不是以 "115-" 開頭,直接原樣傳回),不會意外砍到內容。
export function albumUrlSlug(id: string, year: string): string {
	const prefix = `${year}-`;
	return id.startsWith(prefix) ? id.slice(prefix.length) : id;
}
